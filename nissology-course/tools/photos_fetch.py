"""Download the course photographs listed in content/photos_src.py and write content/photos.py.

Commons metadata (author, licence, page) is read with one batched API call per 40 titles, and images are
fetched at 1600 px with polite spacing. NASA images come from the NASA Image and Video Library (public domain).
python3 tools/photos_fetch.py
"""
import io, json, os, re, sys, time, urllib.parse, urllib.request
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "content"))
from photos_src import COMMONS, NASA  # noqa: E402

OUT = os.path.join(ROOT, "site", "media", "photos")
UA = {"User-Agent": "NissologyCourse/1.0 (educational course build; https://github.com/jvi-44)"}
try:
    from photos import PHOTOS as OLD  # noqa: E402
except Exception:
    OLD = {}


def get(url, tries=8):
    for k in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=120) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            wait = int(e.headers.get("retry-after", 20)) + 3 if e.code == 429 else 10 * (k + 1)
            print(f"  HTTP {e.code}; waiting {wait}s", flush=True); time.sleep(wait)
        except Exception as e:
            print(f"  {e}; retrying", flush=True); time.sleep(10 * (k + 1))
    raise RuntimeError(url)


def clean(s):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", s or "")).strip()


def save(data, pid):
    im = Image.open(io.BytesIO(data)).convert("RGB")
    im.thumbnail((1600, 1600))
    im.save(os.path.join(OUT, f"{pid}.jpg"), quality=82, optimize=True, progressive=True)
    return im.size


def main():
    os.makedirs(OUT, exist_ok=True)
    photos = {}
    items = list(COMMONS.items())
    meta = {}
    for i in range(0, len(items), 40):
        titles = "|".join(t for _, (t, _) in items[i:i + 40])
        q = urllib.parse.urlencode({"action": "query", "titles": titles, "prop": "imageinfo", "iiprop": "url|size|extmetadata", "iiurlwidth": 1600, "format": "json"})
        d = json.loads(get("https://commons.wikimedia.org/w/api.php?" + q))
        norm = {n["to"]: n["from"] for n in d["query"].get("normalized", [])}
        for p in d["query"]["pages"].values():
            if "imageinfo" in p:
                meta[norm.get(p["title"], p["title"])] = p["imageinfo"][0]
        time.sleep(3)
    for pid, (title, caption) in items:
        ii = meta.get(title)
        if not ii:
            print("MISSING on Commons:", pid, title); continue
        m = ii.get("extmetadata", {})
        author = clean(m.get("Artist", {}).get("value")) or "Unknown"
        lic = clean(m.get("LicenseShortName", {}).get("value")) or "see source"
        dest = os.path.join(OUT, f"{pid}.jpg")
        if not os.path.exists(dest):
            print("download", pid, flush=True)
            fname = title.split(":", 1)[1]
            w = min(1600, ii.get("width") or 1600)
            url = "https://commons.wikimedia.org/w/thumb.php?" + urllib.parse.urlencode({"f": fname, "w": w})
            save(get(url), pid); time.sleep(2)
        photos[pid] = dict(caption=caption, alt=caption, author=author[:120], license=lic, page=ii["descriptionurl"], source="Wikimedia Commons",
                           credit=f"{author[:70]} · {lic} · Wikimedia Commons")
    for pid, (nid, caption, credit) in NASA.items():
        dest = os.path.join(OUT, f"{pid}.jpg")
        if not os.path.exists(dest):
            assets = json.loads(get(f"https://images-api.nasa.gov/asset/{nid}"))["collection"]["items"]
            hrefs = [a["href"] for a in assets]
            pick = next((h for h in hrefs if "~large." in h), None) or next(h for h in hrefs if "~orig." in h)
            save(get(pick.replace("http://", "https://")), pid)
        photos[pid] = dict(caption=caption, alt=caption, author=credit, license="Public domain (NASA)", page=f"https://images.nasa.gov/details/{nid}",
                           source="NASA Image and Video Library", credit=f"{credit} · Public domain")
    with open(os.path.join(ROOT, "content", "photos.py"), "w") as f:
        f.write('"""Generated by tools/photos_fetch.py from content/photos_src.py. Do not edit by hand."""\n\nPHOTOS = ')
        f.write(json.dumps(photos, indent=1, ensure_ascii=False))
        f.write("\n")
    print(len(photos), "photos")


if __name__ == "__main__":
    main()
